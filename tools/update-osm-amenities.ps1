<#
  Refreshes js/amenities-data.js, the OpenStreetMap snapshot used by the
  "Confort du parcours / Комфорт маршрута" section of carte.html.

  It downloads cafés, drinking water, benches, parks, toilets and public
  transport stops in central Almaty from the Overpass API, keeps only the
  tags the map uses, and rewrites the data file. See tools/README.md.

  Usage (from the project folder):
    powershell -ExecutionPolicy Bypass -File tools\update-osm-amenities.ps1
#>
param(
  # Where to write the data file. Defaults to js/amenities-data.js.
  [string]$Out = (Join-Path (Split-Path $PSScriptRoot -Parent) "js\amenities-data.js"),
  # Write even if the server's data is older than the current file.
  [switch]$Force
)

$ErrorActionPreference = "Stop"
$ProgressPreference = "SilentlyContinue"

# Area around the six places, with about 650 m of margin: south, west, north, east.
$bbox = "43.221,76.889,43.256,76.965"

$query = "[out:json][timeout:180][bbox:$bbox];(" +
  'nwr["amenity"~"^(cafe|drinking_water|toilets|bench)$"];' +
  'nwr["leisure"="park"];' +
  'nwr["highway"="bus_stop"];' +
  'nwr["railway"~"^(tram_stop|subway_entrance)$"];' +
  'nwr["station"="subway"];' +
  ");out center tags;"

# Public Overpass servers are often busy, so try several in turn.
$endpoints = @(
  "https://overpass-api.de/api/interpreter",
  "https://maps.mail.ru/osm/tools/overpass/api/interpreter",
  "https://overpass.kumi.systems/api/interpreter"
)
$headers = @{ "User-Agent" = "almaty-sans-frontieres-school-project/1.0" }

$raw = $null
foreach ($endpoint in $endpoints) {
  Write-Host "Downloading from $endpoint ..."
  try {
    $response = Invoke-WebRequest -Uri $endpoint -Method Post -Body @{ data = $query } -Headers $headers -UseBasicParsing -TimeoutSec 240
    $raw = [Text.Encoding]::UTF8.GetString($response.RawContentStream.ToArray())
    break
  } catch {
    Write-Host "  failed: $($_.Exception.Message)"
  }
}
if (-not $raw) { throw "No Overpass server answered. Try again later; js/amenities-data.js was not changed." }

$json = $raw | ConvertFrom-Json
if (-not $json.elements -or $json.elements.Count -eq 0) {
  throw "Overpass returned no places. js/amenities-data.js was not changed."
}

# Only the tags the map reads (see js/map.js).
$keep = "name", "name:ru", "name:fr", "name:kk", "addr:street", "addr:housenumber", "addr:full", "opening_hours",
  "wheelchair", "toilets:wheelchair", "route_ref", "access", "amenity", "leisure", "highway", "railway", "station"
$inv = [Globalization.CultureInfo]::InvariantCulture
$rows = New-Object System.Collections.Generic.List[string]
foreach ($e in $json.elements) {
  $lat = if ($e.lat) { $e.lat } else { $e.center.lat }
  $lon = if ($e.lon) { $e.lon } else { $e.center.lon }
  if (-not $lat) { continue }
  $tags = [ordered]@{}
  foreach ($k in $keep) { $v = $e.tags.$k; if ($v) { $tags[$k] = [string]$v } }
  $rows.Add(('["{0}",{1},{2},{3},{4}]' -f $e.type.Substring(0, 1), $e.id,
    ([double]$lat).ToString("0.######", $inv), ([double]$lon).ToString("0.######", $inv),
    ($tags | ConvertTo-Json -Compress)))
}

$date = $json.osm3s.timestamp_osm_base.Substring(0, 10)

# Some mirrors lag months behind; never replace newer data with older.
if ((Test-Path $Out) -and -not $Force) {
  $current = [regex]::Match([IO.File]::ReadAllText($Out), 'date: "(\d{4}-\d{2}-\d{2})"').Groups[1].Value
  if ($current -and $date -lt $current) {
    throw "This server's data ($date) is older than the current file ($current). Nothing was changed. Try again later, or add -Force to use it anyway."
  }
}

$js = "/* OpenStreetMap snapshot for the optional comfort layers on carte.html.`n" +
  "   Source: Overpass API, OSM data as of $date, (c) OpenStreetMap contributors, ODbL.`n" +
  "   Area: central Almaty around the six places. Rows: [type, id, lat, lng, tags].`n" +
  "   Generated by tools/update-osm-amenities.ps1. */`n" +
  "window.ASF = window.ASF || {};`n" +
  "window.ASF.amenityData = {`n  date: `"$date`",`n  items: [`n    " + ($rows -join ",`n    ") + "`n  ]`n};`n"
[IO.File]::WriteAllText($Out, $js, (New-Object Text.UTF8Encoding $false))

Write-Host ("Wrote {0} places, {1:N0} KB, OSM data as of {2}, to {3}" -f $rows.Count, ((Get-Item $Out).Length / 1KB), $date, $Out)
Write-Host "Remember to update the date in the OpenStreetMap entry of 'sources' in js/content.js."
